// Generate src/styles/tokens.css (CSS custom properties) from design/tokens.json.
// tailwind.config.ts maps its theme onto these variables, so tokens.json is the single source.
// Usage: node design/scripts/build-theme.mjs  (runs before every build)
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../tokens.json', import.meta.url), 'utf8'));

const vars = {
  '--pulse-font-sans': t.font.family.value,
  '--pulse-bg': t.color.background.value,
  '--pulse-bg-alt': t.color.backgroundAlt.value,
  '--pulse-ink': t.color.text.value,
  '--pulse-ink-2': t.color.textSecondary.value,
  '--pulse-ink-on-light': t.color.textOnLight.value,
  '--pulse-ink-2-on-light': t.color.textSecondaryOnLight.value,
  '--pulse-hairline': t.color.hairline.value,
  '--pulse-neutral-lightest': t.color.neutralLightest.value,
  '--pulse-neutral-darker': t.color.neutralDarker.value,
  '--pulse-accent': t.color.accent.value,
  '--pulse-status-on-track': t.status.onTrack.value,
  '--pulse-status-at-risk': t.status.atRisk.value,
  '--pulse-status-off-track': t.status.offTrack.value,
  '--pulse-status-missing': t.status.missing.value,
  '--pulse-chart-series': t.chart.series.value,
  '--pulse-chart-target': t.chart.target.value,
  '--pulse-chart-grid': t.chart.gridline.value,
  '--pulse-gutter': t.space.pageGutter.desktop,
  '--pulse-cell': t.space.cellPadding,
  '--pulse-block': t.space.blockGap,
  '--pulse-hero': t.space.heroPaddingTop,
};
for (const [name, s] of Object.entries(t.type)) {
  vars[`--pulse-text-${name}`] = s.size;
  vars[`--pulse-text-${name}-lh`] = String(s.lineHeight);
  vars[`--pulse-text-${name}-ls`] = s.letterSpacing;
  vars[`--pulse-text-${name}-weight`] = String(s.weight);
}

const body = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n');
const css = `/* GENERATED by design/scripts/build-theme.mjs from design/tokens.json. Do not edit by hand. */
:root {
${body}
}

/* The gutter widens below 768px. */
@media screen and (max-width: 767px) {
  :root {
    --pulse-gutter: ${t.space.pageGutter.mobile};
  }
}
`;
writeFileSync(new URL('../../src/styles/tokens.css', import.meta.url), css);
console.log(`tokens.css: ${Object.keys(vars).length} variables`);
